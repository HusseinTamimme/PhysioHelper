def calculate_3d_angle(a, b, c):
    a, b, c = np.array(a), np.array(b), np.array(c)
    ba = a - b
    bc = c - b
    cosine_angle = np.dot(ba, bc) / (np.linalg.norm(ba) * np.linalg.norm(bc) + 1e-6)
    angle = np.arccos(np.clip(cosine_angle, -1.0, 1.0))
    return np.degrees(angle)

def get_landmark(landmarks, index):
    lm = landmarks[index]
    return [lm.x, lm.y, lm.z]

class RepTracker:
    def __init__(self):
        self.state = "SETUP"
        self.total_reps = 0
        self.perfect_reps = 0
        self.current_rep_flawless = True

    def update(self, span_angle, mistakes):
        if self.state in ["ROTATING", "T_POSE", "RETURNING"] and len(mistakes) > 0:
            self.current_rep_flawless = False

        if self.state == "SETUP":
            if span_angle > SPAN_SETUP + 10:
                self.state = "ROTATING"
                self.current_rep_flawless = (len(mistakes) == 0)
        elif self.state == "ROTATING":
            if span_angle >= SPAN_HOLD:
                self.state = "T_POSE"
            elif span_angle <= SPAN_SETUP:
                self.state = "SETUP"
        elif self.state == "T_POSE":
            if span_angle < SPAN_HOLD - 15:
                self.state = "RETURNING"
        elif self.state == "RETURNING":
            if span_angle <= SPAN_SETUP + 15:
                self.total_reps += 1
                if self.current_rep_flawless:
                    self.perfect_reps += 1
                self.state = "SETUP"

        return self.state, self.current_rep_flawless

def evaluate_full_body(world_landmarks):
    l_sh = get_landmark(world_landmarks, 11)
    r_sh = get_landmark(world_landmarks, 12)
    l_elb = get_landmark(world_landmarks, 13)
    r_elb = get_landmark(world_landmarks, 14)
    l_wr = get_landmark(world_landmarks, 15)
    r_wr = get_landmark(world_landmarks, 16)
    l_hip = get_landmark(world_landmarks, 23)
    r_hip = get_landmark(world_landmarks, 24)
    l_kn = get_landmark(world_landmarks, 25)
    r_kn = get_landmark(world_landmarks, 26)
    l_ank = get_landmark(world_landmarks, 27)
    r_ank = get_landmark(world_landmarks, 28)

    mid_sh = [(l_sh[0]+r_sh[0])/2, (l_sh[1]+r_sh[1])/2, (l_sh[2]+r_sh[2])/2]

    ang_l_elbow = calculate_3d_angle(l_sh, l_elb, l_wr)
    ang_r_elbow = calculate_3d_angle(r_sh, r_elb, r_wr)
    ang_l_knee = calculate_3d_angle(l_hip, l_kn, l_ank)
    ang_r_knee = calculate_3d_angle(r_hip, r_kn, r_ank)
    ang_span = calculate_3d_angle(l_wr, mid_sh, r_wr)

    ang_l_spine = calculate_3d_angle(l_sh, l_hip, l_kn)
    ang_r_spine = calculate_3d_angle(r_sh, r_hip, r_kn)
    ang_spine = (ang_l_spine + ang_r_spine) / 2.0

    ang_l_elev = calculate_3d_angle(l_hip, l_sh, l_wr)
    ang_r_elev = calculate_3d_angle(r_hip, r_sh, r_wr)
    hip_z_diff = abs(l_hip[2] - r_hip[2])

    colors = {}
    mistakes = []

    l_arm_ok = True
    if ang_l_elbow < ELBOW_MIN:
        mistakes.append(f"Straighten L Arm")
        l_arm_ok = False
    if not (ARM_HEIGHT_MIN <= ang_l_elev <= ARM_HEIGHT_MAX):
        mistakes.append(f"L Arm Drop/Raise")
        l_arm_ok = False
    colors['l_arm'] = COLOR_GREEN if l_arm_ok else COLOR_RED

    r_arm_ok = True
    if ang_r_elbow < ELBOW_MIN:
        mistakes.append(f"Straighten R Arm")
        r_arm_ok = False
    if not (ARM_HEIGHT_MIN <= ang_r_elev <= ARM_HEIGHT_MAX):
        mistakes.append(f"R Arm Drop/Raise")
        r_arm_ok = False
    colors['r_arm'] = COLOR_GREEN if r_arm_ok else COLOR_RED

    if KNEE_MIN <= ang_l_knee <= KNEE_MAX:
        colors['l_leg'] = COLOR_GREEN
    else:
        colors['l_leg'] = COLOR_RED
        mistakes.append(f"Fix L Knee")

    if KNEE_MIN <= ang_r_knee <= KNEE_MAX:
        colors['r_leg'] = COLOR_GREEN
    else:
        colors['r_leg'] = COLOR_RED
        mistakes.append(f"Fix R Knee")

    torso_ok = True
    if ang_spine < SPINE_MIN:
        mistakes.append(f"Keep Back Straight")
        torso_ok = False
    if hip_z_diff > HIP_TWIST_MAX:
        mistakes.append(f"Hips Twisting!")
        torso_ok = False

    if not torso_ok:
        colors['torso'] = COLOR_ORANGE if ang_spine >= SPINE_MIN else COLOR_RED
    else:
        colors['torso'] = COLOR_GREEN

    metrics = {
        "l_el": ang_l_elbow, "r_el": ang_r_elbow,
        "l_elev": ang_l_elev, "r_elev": ang_r_elev,
        "l_kn": ang_l_knee, "r_kn": ang_r_knee,
        "spine": ang_spine, "span": ang_span
    }
    return colors, mistakes, metrics

def draw_dynamic_skeleton(frame, pixel_landmarks, colors, width, height):
    limb_groups = {
        'l_arm': [(11, 13), (13, 15)],
        'r_arm': [(12, 14), (14, 16)],
        'l_leg': [(23, 25), (25, 27)],
        'r_leg': [(24, 26), (26, 28)],
        'torso': [(11, 12), (11, 23), (12, 24), (23, 24)]
    }

    for group_name, connections in limb_groups.items():
        color = colors.get(group_name, COLOR_WHITE)
        for p1, p2 in connections:
            x1 = int(pixel_landmarks[p1].x * width)
            y1 = int(pixel_landmarks[p1].y * height)
            x2 = int(pixel_landmarks[p2].x * width)
            y2 = int(pixel_landmarks[p2].y * height)

            cv2.line(frame, (x1, y1), (x2, y2), color, 6)
            cv2.circle(frame, (x1, y1), 8, color, -1)
            cv2.circle(frame, (x2, y2), 8, color, -1)

