            rep_color = COLOR_GREEN if is_flawless else COLOR_RED
            rep_msg = "Form: Flawless" if is_flawless else "Form: Broken"
            cv2.putText(frame_rgb, f"Phase: {state} | {rep_msg}", (20, 120), cv2.FONT_HERSHEY_SIMPLEX, 0.6, rep_color, 2)

