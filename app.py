# Biomechanical Thresholds
KNEE_MIN = 70
KNEE_MAX = 120
ELBOW_MIN = 145
SPINE_MIN = 150
SPAN_SETUP = 45
SPAN_HOLD = 150
ARM_HEIGHT_MIN = 75
ARM_HEIGHT_MAX = 110
HIP_TWIST_MAX = 0.15

# Colors (RGB format for Streamlit/Web)
COLOR_GREEN = (0, 255, 0)
COLOR_RED = (255, 0, 0)
COLOR_WHITE = (255, 255, 255)
COLOR_ORANGE = (255, 165, 0)
COLOR_YELLOW = (255, 255, 0)

